#!/bin/sh

# Exports Swashbuckle's contract and generates the pinned NSwag client.
# The roadmap and nswag.json define how frontend code consumes its output.
set -eu

script_directory=$(
  CDPATH= cd -- "$(dirname -- "$0")" && pwd
)
repository_root=$(
  CDPATH= cd -- "$script_directory/.." && pwd
)
api_project="$repository_root/backend/src/StarDustTravelAgency.Api"
openapi_file="$repository_root/openapi/star-dust-v1.json"
temporary_openapi_file="$openapi_file.tmp"
generated_client="$repository_root/frontend/src/api/generated/star-dust-api.ts"
header_pattern='s#^//     Generated using the NSwag toolchain.*#'
header_replacement='//     Generated by pinned NSwag; see nswag.json.#'
api_log=$(mktemp)
api_pid=""
api_url="http://127.0.0.1:5099"
contract_db='Host=127.0.0.1;Port=65432;'
contract_db="${contract_db}Database=star_dust;"
contract_db="${contract_db}Username=star_dust;"
contract_db="${contract_db}Password=contract-export;"
contract_db="${contract_db}Timeout=1;"
contract_db="${contract_db}Command Timeout=1"

# Stops only the API started below and removes its temporary working files.
cleanup() {
  if [ -n "$api_pid" ]; then
    kill "$api_pid" 2>/dev/null || true
    wait "$api_pid" 2>/dev/null || true
  fi

  rm -f "$api_log" "$temporary_openapi_file"
}

trap cleanup EXIT INT TERM

dotnet build "$api_project" --no-restore --disable-build-servers

env \
  ASPNETCORE_URLS="$api_url" \
  Swagger__Enabled=true \
  ConnectionStrings__Postgres="$contract_db" \
  dotnet run \
    --project "$api_project" \
    --no-build \
    --no-launch-profile \
    >"$api_log" 2>&1 &
api_pid=$!

attempt=0
until curl \
  --fail \
  --silent \
  --output "$temporary_openapi_file" \
  "$api_url/swagger/v1/swagger.json"
do
  attempt=$((attempt + 1))

  if ! kill -0 "$api_pid" 2>/dev/null || [ "$attempt" -ge 40 ]; then
    echo "The temporary API did not expose its OpenAPI document." >&2
    sed -n '1,160p' "$api_log" >&2
    exit 1
  fi

  sleep 0.25
done

mv "$temporary_openapi_file" "$openapi_file"

cd "$repository_root"
dotnet tool run nswag run nswag.json
sed -i "${header_pattern}${header_replacement}" "$generated_client"
npm --prefix "$repository_root/frontend" run format:api
